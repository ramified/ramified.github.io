'use strict';
const assert=require('node:assert/strict'),model=require('./math_workspace_presentation.js');
const legacy={id:'source-C',kind:'chain-complex',objects:['A','B'],maps:['f'],display:'snake-les',snakeLayout:{firstRowSize:3,startIndex:0},selected:false};
const split=model.split('complex',{legacy});
assert.deepEqual(split.data.legacy,{id:'source-C',kind:'chain-complex',objects:['A','B'],maps:['f']});
assert.deepEqual(split.view.complex,{display:'snake-les',snakeLayout:legacy.snakeLayout,selected:false});
assert.equal(legacy.display,'snake-les','extraction never mutates the source');
const payload={type:'ordinary',dimension:3,domainId:'X',codomainId:'Y',labelT:.4,labelOffset:12,hiddenOnCanvas:true,curve:{kind:'bezier',points:[]},modified:true};
const map=model.split('map',{workspaceSheafComplex:{payload}});
assert.deepEqual(map.data.workspaceSheafComplex.payload,{type:'ordinary',dimension:3,domainId:'X',codomainId:'Y'});
assert.deepEqual(model.layout(map.view.sheaf),{x:.4,y:12,mode:'map-curve',hidden:true,curve:payload.curve,modified:true});
assert.deepEqual(model.split('sphere',{radius:3,center:[0,0,0]}).data,{radius:3,center:[0,0,0]});
assert.deepEqual(model.split('mosaic-space',{backgroundMetric:'hyperbolic'}).data,{backgroundMetric:'hyperbolic'});
assert.deepEqual(model.split('dynkin',{quiver:{'0-1':-1}}).data,{quiver:{'0-1':-1}});
const backup={assets:[{kind:'complex',id:'C',data:{legacy}},{kind:'map',id:'f',data:{workspaceSheafComplex:{payload}}}],workspace:{},assetCards:{instances:[{targetRef:{kind:'complex',id:'C'},draft:{data:{legacy}},baseDefinition:{data:{legacy}}}]}};
model.migrateWorkspace(backup);
assert.deepEqual(backup.assets[0].data,split.data);assert.deepEqual(backup.workspace.viewDefaults[0],['complex:C',split.view]);
assert.equal(backup.assetCards.instances[0].draft.data.legacy.display,undefined);
assert.equal(backup.assetCards.instances[0].baseDefinition.data.legacy.selected,undefined);
const once=JSON.stringify(backup);model.migrateWorkspace(backup);assert.equal(JSON.stringify(backup),once,'migration is idempotent');
assert.throws(()=>model.validate([['complex:C',{}],['complex:C',{}]],backup.assets),/Invalid/);
assert.throws(()=>model.validate([['complex:gone',{}]],backup.assets),/Invalid/);
assert.throws(()=>model.validate([['complex:C',{math:{}}]],backup.assets),/Invalid/);
console.log('Presentation separation: mathematical definitions, provenance, imported view defaults, draft baselines and idempotent backups passed');
