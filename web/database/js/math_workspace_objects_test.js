assert.throws(() => model.prepareRootImport('strands',{ ...legacyWord, strandCount: 4 }));
assert.throws(() => model.prepareRootImport('strands',{ ...legacyWord, groupType: 'E6' }));
assert.deepEqual(model.prepareRootImport('dynkin',{ calculator: 'Dynkin diagram calculator', version: 1, typeKey: 'A', rank: 3, selectedVertex: 2 }).data.vertices, [2]);
console.log('math_workspace_objects_test: Dynkin/Strands references, rank conversion, optional quivers, lossless invalidation and strict legacy imports passed');
