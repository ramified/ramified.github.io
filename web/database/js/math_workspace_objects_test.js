'use strict';
const assert = require('node:assert/strict');
const model = require('./math_workspace_objects.js');
const matrix = model.normalize('matrix', 'matrix', { rows: 2, cols: 3 });
assert.deepEqual(matrix.entries, [['1','0','0'],['0','1','0']]);
assert.throws(() => model.normalize('matrix', 'matrix', { rows: 9 }));
assert.throws(() => model.normalize('matrix', 'matrix', { rows: 2, cols: 2, entries: [['1']] }));
assert.throws(() => model.normalize('matrix', 'matrix', { finiteFieldPrime: 4 }));
assert.equal(model.normalize('matrix', 'matrix', { finiteFieldPrime: 999983 }).finiteFieldPrime, 999983);
const field = {kind:'field',id:'k',type:'field',name:'K',data:model.normalize('field','field',{dataType:'finite-field',finiteFieldPrime:13})};
const linkedMatrix = {kind:'matrix',id:'linked',type:'matrix',name:'A',data:model.normalize('matrix','matrix',{rows:2,cols:3,field:'field:k'})};
const linkedContext = {type:'matrix-view',refs:{matrix:'matrix:linked'}};
const fieldContext = model.contextFor(linkedContext,[linkedMatrix,field]);
assert.deepEqual(fieldContext.missing,[]);
assert.equal(fieldContext.objects.matrix.data.finiteFieldPrime,13);
assert.equal(fieldContext.objects.matrix.data.dataType,'finite-field');
assert.equal(fieldContext.objects.matrix.data.cols,3,'a field changes coefficients without changing matrix dimensions');
field.data=model.normalize('field','field',{dataType:'finite-field',finiteFieldPrime:17});
assert.notEqual(model.contextFor(linkedContext,[linkedMatrix,field]).signature,fieldContext.signature,'shared field changes invalidate dependent computations');
assert(model.contextFor(linkedContext,[linkedMatrix]).missing.length,'deleted fields remain explicit missing references');
assert.throws(()=>model.normalize('field','field',{dataType:'finite-field',finiteFieldPrime:15}));
const graphAssets = [{ kind: 'category', id: 'c', name: 'C', data: model.normalize('category', 'category') }, { kind: 'functor', id: 'f', name: 'F', data: model.normalize('functor', 'functor', { domain: 'category:c', codomain: 'category:c' }) }];
const sheafGraph = [
  {kind:'variety',id:'x',name:'X',type:'projective',data:{dimension:'2'},dependencies:[]},
  {kind:'sheaf',id:'e',name:'E',type:'locally-free',data:{base:'variety:x',rank:'2'},dependencies:[{kind:'variety',id:'x'}]},
  {kind:'map',id:'f',name:'f',type:'sheaf',data:{domain:'sheaf:e',codomain:'sheaf:e'},dependencies:[{kind:'sheaf',id:'e'}]}
];
const sheafView = {type:'sheaf-view',refs:{asset:'map:f'}};
const sheafContext = model.contextFor(sheafView,sheafGraph);
assert.deepEqual(sheafContext.missing,[]);
assert.deepEqual(Object.values(sheafContext.objects).map(model.keyOf),['map:f','sheaf:e','variety:x'],'include transitive bases and deduplicate repeated endpoints');
assert.deepEqual(model.contextFor(sheafView,sheafGraph.slice(1)).missing,['variety:x']);
assert(model.contextFor({type:'sheaf-view',refs:{asset:'map:missing'}},sheafGraph).missing.length);
sheafGraph[0].name='Y';
assert.notEqual(model.contextFor(sheafView,sheafGraph).signature,sheafContext.signature,'dependency label changes refresh the drawing');
const overviewContext = model.contextFor({type:'sheaf-view',refs:{asset:'variety:x',nodes:['map:f','sheaf:e','variety:x','map:f'],active:'sheaf:e'}},sheafGraph);
assert.deepEqual(new Set(Object.values(overviewContext.objects).map(model.keyOf)),new Set(['map:f','sheaf:e','variety:x']),'an overview accumulates objects and deduplicates dependencies');
assert.equal(Object.values(overviewContext.objects).length,3);
assert.deepEqual(model.contextFor({type:'sheaf-view',refs:{nodes:[]}},sheafGraph).missing,[],'empty overviews do not create a default object');
for(const kind of ['variety','sheaf','map']) assert.equal(model.capabilityFor({kind}).open,'sheaf-view');
assert.equal(model.capabilityFor({kind:'variety',type:'toric'}).open,'sheaf-view');
assert.equal(model.capabilityFor({kind:'variety',type:'toric'}).modify,'toric-variety-input');
const scene = { type: 'category-diagram', refs: { nodes: ['functor:f'] } };
assert.equal(Object.keys(model.contextFor(scene, graphAssets).objects).length, 2, 'include endpoint dependencies once for an endofunctor');
assert.equal(model.contextFor(scene, graphAssets.slice(1)).missing.length, 2, 'missing endpoints stay missing');
const beforeRename = model.contextFor(scene, graphAssets).signature; graphAssets[0].name = 'D';
assert.notEqual(model.contextFor(scene, graphAssets).signature, beforeRename, 'diagram labels follow renames');
const preset = { kind: 'category-calculator-prototype', categories: [{ id: 'c', label: 'C' }], functors: [{ id: 'f', domainId: 'c', codomainId: 'c' }] };
assert.equal(model.prepareCategoryGraph(preset).functors.length, 1);
assert.throws(() => model.prepareCategoryGraph({ ...preset, categories: [] }));
assert.throws(() => model.prepareCategoryGraph({ ...preset, categories: [...preset.categories, ...preset.categories] }));
const rows = text => model.normalize('young', 'partition', { partition: text });
assert.deepEqual(rows('4, 2, 1'), { rows: [4, 2, 1], partition: '4, 2, 1' });
assert.deepEqual(rows(''), { rows: [], partition: '' });
for (const draft of ['4,', '-', '1e', '2, 4', '-1', '26']) assert.throws(() => rows(draft));
assert.deepEqual(model.normalize('young', 'generalized', { partition: '2, 0, -1' }).rows, [2, 0, -1]);
assert.throws(() => model.normalize('lie', 'simple', { family: 'D', rank: 2 }));
assert.equal(model.normalize('lie', 'simple', { family: 'E6', rank: 3 }).rank, 6);
const assets = [
  { kind: 'young', id: 'a', type: 'partition', data: rows('2,1') },
  { kind: 'young', id: 'b', type: 'partition', data: rows('1') },
  { kind: 'lie', id: 'g', type: 'simple', data: { family: 'A', rank: 3 } },
  { kind: 'variety', id: 'x', type: 'grassmannian', data: { r: 2, n: 4 } }
];
const c = { type: 'lr', refs: { lambda: 'young:a', mu: 'young:b', lie: 'lie:g' } };
const first = model.contextFor(c, assets);
const branching = { type: 'branching', refs: { lambda: 'young:a' } };
assert.deepEqual(model.contextFor(branching, assets).missing, ['Young diagram μ']);
assert.deepEqual(model.contextFor({ ...branching, rule: 'sum-gl' }, assets).missing, []);
assert.equal(model.contextFor({ ...branching, rule: 'sum-gl', refs: { ...branching.refs, mu: 'young:b' } }, assets).objects.mu, undefined, 'single-input rules ignore a retained second reference');
assert.deepEqual(first.missing, []);
assert.equal(first.objects.lambda.id, 'a');
assert.notEqual(model.contextFor({ ...c, refs: { ...c.refs, lambda: 'young:b', mu: 'young:a' } }, assets).signature, first.signature, 'ordered references distinguish asymmetric operations');
assert.deepEqual(model.contextFor({ ...c, refs: { ...c.refs, mu: 'young:a' } }, assets).missing, [], 'the same object can occupy both input roles');
assets[2].data.rank = 4;
assert.notEqual(model.contextFor(c, assets).signature, first.signature, 'changing the Lie asset invalidates dependent calculations');
assert.deepEqual(model.contextFor(c, assets.filter(a => a.id !== 'b')).missing, ['Young diagram μ'], 'deletion leaves a missing reference, not an implicit substitute');
assets[0].type = 'generalized';
assert(model.contextFor(c, assets).missing.includes('Young diagram λ'), 'ordinary engines never coerce generalized objects');
assets[0].type = 'partition';
const cup = { type: 'grassmannian', refs: { lambda: 'young:a', mu: 'young:b', space: 'variety:x' } };
assert.deepEqual(model.contextFor(cup, assets).missing, []);
assets[3].data.r = 1;
assert(model.contextFor(cup, assets).missing.some(text => text.includes('must fit')), 'Grassmannian bounds come from its Asset');
console.log('math_workspace_objects_test: typed objects, ordered references, shared Lie inputs, invalidation and Grassmannian bounds passed');
const root = { kind: 'lie', id: 'r', type: 'simple', data: model.normalize('lie', 'simple', { family: 'A', rank: 13 }) };
assert.deepEqual(model.strandContext(root.data), { groupType: 'symmetric', strandCount: 14 });
assert.equal(model.lieEngineIssues(root.data, 'strand').length, 0);
assert.equal(model.lieEngineIssues(root.data, 'dynkin').length, 1);
assert.deepEqual(model.strandContext({ family: 'D', rank: 4 }), { groupType: 'D', strandCount: 4 });
assert.throws(() => model.strandContext({ family: 'G2', rank: 2 }));
assert.deepEqual(model.dynkinEdges({ family: 'D', rank: 4 }), ['0-1','1-2','1-3']);
assert.deepEqual(model.dynkinEdges({ family: 'E6', rank: 6 }), ['0-1','1-2','2-3','3-4','2-5']);
const strand = { kind: 'strands', id: 's', data: model.normalize('strands', 'strands', { lie: 'lie:r', generators: [{ family: 'braid', index: 12, sign: -1 }, { family: 'kl', index: 1 }] }) };
const word = JSON.stringify(strand.data), calc = { type: 'strands-calculation', refs: { strands: 'strands:s' } };
assert.deepEqual(model.contextFor(calc, [root,strand]).missing, []);
root.data.rank = 4;
assert.match(model.contextFor(calc, [root,strand]).missing.join(' '), /indices/);
assert.equal(JSON.stringify(strand.data), word, 'rank shrink must preserve the entire typed word');
assert(model.contextFor(calc, [strand]).missing.length);
assert.deepEqual(model.contextFor({ type: 'strands-relations', refs: {} }, []).missing, []);
const basis = { type: 'strands-basis', refs: { lie: 'lie:r' } }, signature = model.contextFor(basis,[root,strand]).signature;
strand.data.generators = [];
assert.equal(model.contextFor(basis,[root,strand]).signature, signature, 'basis depends on Lie type only');
const dynkin = { kind: 'dynkin', id: 'd', data: model.normalize('dynkin','dynkin',{ lie: 'lie:r', vertices: [1,3], quiver: { '0-1': 1,'1-2': -1,'2-3': 1 } }) };
assert.deepEqual(model.rootObjectIssues(dynkin,root), []);
root.data.rank = 3;
assert.match(model.rootObjectIssues(dynkin,root).join(' '), /quiver edges/);
assert.throws(() => model.normalize('strands','strands',{ generators: [{ family: 'unknown', index: 1 }] }));
assert.throws(() => model.normalize('strands','strands',{ generators: [{ family: 'braid', index: 1 }] }));
