/* Build the independent study from the current player page; no shared files are edited. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const BUILD = '20261028-6';
const check = process.argv.includes('--check');
function emit(filename, contents) {
  if (check) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8').replace(/\r\n/g, '\n') !== contents.replace(/\r\n/g, '\n')) throw new Error('Rebuild required: ' + filename);
  } else fs.writeFileSync(filename, contents);
}
const buildRenderer = require('./ramified_minigames_study_render_build.js');
emit(path.join(__dirname, 'ramified_minigames_study_engine.js'), buildRenderer(fs.readFileSync(path.join(__dirname, 'ramified_minigames_setup.js'), 'utf8')));
let html = fs.readFileSync(path.join(root, 'ramified_minigames.html'), 'utf8').replace(/\r\n/g, '\n');
let player = fs.readFileSync(path.join(__dirname, 'ramified_minigames_player.js'), 'utf8').replace(/\r\n/g, '\n');
player = '/* Generated by ramified_minigames_study_build.js. Study only. */\n' + player;
// Isolate the study save slots (including legacy migration) from the original page.
player = player.replace('localStorage.getItem(key), setItem: (key, value) => localStorage.setItem(key, value)',
  "localStorage.getItem('design-study:' + key), setItem: (key, value) => localStorage.setItem('design-study:' + key, value)");
player = player.replace('for (const item of engine.games()) {',
  "const order = ['2048', 'connect-four', 'gomoku', 'go', 'reversi', 'sokoban', 'hex', 'fide-chess', 'chinese-checkers', 'billiards', 'lianliankan'];\n      for (const item of [...engine.games()].sort((a, b) => order.indexOf(a.mode) - order.indexOf(b.mode))) {");
// Separate board/control compatibility styles from the new shell. Do not load
// the old player shell in this page, and do not edit shared Mosaic styles.
const embedded = html.match(/<style>([\s\S]*?)<\/style>/)[1];
let base = ['site.css', 'site_i18n.css', 'import_export_panel.css']
  .map(name => fs.readFileSync(path.join(root, 'css', name), 'utf8')).join('\n') + '\n' + embedded;
// Restore the original level picker and board preparation layout, without
// loading the rest of the original player shell over the new title screen.
const originalPlayerCss = fs.readFileSync(path.join(root, 'css/ramified_minigames_player.css'), 'utf8').replace(/\r\n/g, '\n');
const preparationStart = originalPlayerCss.indexOf('.player-page.player-board-page');
const preparationEnd = originalPlayerCss.indexOf('#player-setup-controls,', preparationStart);
const levelsStart = originalPlayerCss.indexOf('#player-level-list {');
const levelsEnd = originalPlayerCss.indexOf('#player-games {', levelsStart);
if ([preparationStart, preparationEnd, levelsStart, levelsEnd].some(index => index < 0)) throw new Error('Original preparation CSS anchors missing.');
const preparationMarker = '/* Original level and preparation layout. */';
base += '\n' + preparationMarker + '\n' + originalPlayerCss.slice(levelsStart, levelsEnd) + originalPlayerCss.slice(preparationStart, preparationEnd);
const mobilePreparationStart = originalPlayerCss.indexOf('@media (max-width: 600px) {');
const mobilePreparationEnd = originalPlayerCss.indexOf('\n}', mobilePreparationStart);
if (mobilePreparationStart < 0 || mobilePreparationEnd < 0) throw new Error('Original mobile preparation CSS anchor missing.');
const mobilePreparation = originalPlayerCss.slice(mobilePreparationStart + originalPlayerCss.slice(mobilePreparationStart).indexOf('{') + 1, mobilePreparationEnd);
const mobilePreparationRules = [...mobilePreparation.matchAll(/([^{}]+)\{([^{}]*)\}/g)]
  .filter(match => /#player-setup-options|#player-setup-players|\.player-controller-picker/.test(match[1]))
  .map(match => match[0]).join('\n');
base += '\n@media (max-width: 600px) {\n' + mobilePreparationRules + '\n}\n';
const toolbarStart = originalPlayerCss.indexOf('#player-toolbar {');
const toolbarEnd = originalPlayerCss.indexOf('.ramified-player #player-action-controls .fullscreen-lianliankan-actions', toolbarStart);
const actionsStart = originalPlayerCss.indexOf('#player-actions {');
const actionsEnd = originalPlayerCss.indexOf('/* Shared player controls.', actionsStart);
const iconSizes = originalPlayerCss.match(/\.ramified-player :is\(\.fullscreen-settings-button, \.fullscreen-action-button,[^}]+\}/);
if ([toolbarStart, toolbarEnd, actionsStart, actionsEnd].some(index => index < 0) || !iconSizes) throw new Error('Original action control CSS anchors missing.');
base += '\n/* Original action drawer and icon toolbar. */\n' + originalPlayerCss.slice(toolbarStart, toolbarEnd) + originalPlayerCss.slice(actionsStart, actionsEnd) + iconSizes[0].replace('.ramified-player ', '.ramified-player #player-toolbar ');
function originalRuleBody(selector) {
  const start = originalPlayerCss.indexOf(selector);
  const brace = originalPlayerCss.indexOf('{', start);
  const end = originalPlayerCss.indexOf('}', brace);
  if (start < 0 || brace < 0 || end < 0) throw new Error('Original control CSS anchor missing: ' + selector);
  return originalPlayerCss.slice(brace + 1, end);
}
base += '\n.ramified-player #player-action-controls .btn, .ramified-player #player-toolbar .btn {' + originalRuleBody('.ramified-player :is(.player-menu-header,') + '}';
base += '\n.ramified-player #player-action-controls :is(select, input[type="number"], input[type="text"]) {' + originalRuleBody('.ramified-player :is(.player-page, .fullscreen-settings-panel, #player-action-controls)') + '}';
const actionFieldsStart = originalPlayerCss.indexOf('.ramified-player :is(.player-page, #player-action-controls) .mosaic-inline-row');
const actionFieldsEnd = originalPlayerCss.indexOf('.ramified-player .calculator-input-action', actionFieldsStart);
if (actionFieldsStart < 0 || actionFieldsEnd < 0) throw new Error('Original action field CSS anchors missing.');
base += '\n' + originalPlayerCss.slice(actionFieldsStart, actionFieldsEnd).replaceAll(':is(.player-page, #player-action-controls)', '#player-action-controls');
// Retain viewport breakpoints, but size legacy controls against the stage too.
const media = [];
base = base.replace(/@media[^\{]+/g, text => { media.push(text); return `__MEDIA_${media.length - 1}__`; });
base = base.replace(/(-?\d*\.?\d+)px\b/g, (_, n) => `calc(${n} * var(--study-px, .1041667cqw))`)
  .replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => `calc(${Number(n) * 16} * var(--study-px, .1041667cqw))`)
  .replace(/(\d)(?:dvh|vh)\b/g, '$1cqh').replace(/(\d)(?:dvw|vw)\b/g, '$1cqw')
  .replace(/__MEDIA_(\d+)__/g, (_, index) => media[index]);
const cleanCompatibility = css => css.replace(/\s*!important/g, '')
    .replace(/(?:-webkit-)?backdrop-filter\s*:[^;]+;/g, '')
    .replace(/(?:box-shadow|transition|animation)\s*:[^;]+;/g, '')
    .replace(/background(?:-image)?\s*:[^;]*(?:linear|radial)-gradient[^;]*;/g, '');
const preparationOffset = base.indexOf(preparationMarker);
emit(path.join(root, 'css/ramified_minigames_study_base.css'),
  '/* Generated compatibility styles; shell lives in study.css. */\n@layer study-base {\n' + cleanCompatibility(base.slice(0, preparationOffset)) + '\n}\n' + cleanCompatibility(base.slice(preparationOffset)));
html = html.replace(/\s*<link rel="stylesheet"[^>]*>/g, '').replace(/<style>[\s\S]*?<\/style>/, '');
html = html.replace('</head>', `<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=STIX+Two+Text:wght@400;600&family=Source+Sans+3:wght@400;600;700&display=swap">
<link rel="stylesheet" href="css/ramified_minigames_study_base.css?v=${BUILD}">
<link rel="stylesheet" href="css/ramified_minigames_study.css?v=${BUILD}">\n</head>`);
html = html.replace('class="ramified-player player-menu-open"', 'class="ramified-player player-menu-open design-study" data-study-page="home"');
html = html.replace('<main class="layout mosaic-layout">', `<main class="layout mosaic-layout" data-build="${BUILD}">`);
html = html.replace('<section id="player-home" class="player-page">', `<section id="player-home" class="player-page">
            <div class="study-introduction"><h2 data-i18n="meta.heading">Ramified Minigames</h2><p data-i18n="study.intro">Games on boards whose edges are glued together.</p></div>`);
html = html.replace('<div id="player-language"></div>', `<div id="player-language"></div><details id="study-workshop"><summary data-i18n="study.workshop">Workshop</summary><p data-i18n="study.workshopHelp">Editing, sound experiments and file tools. These are optional; close this section to return to ordinary settings.</p><div id="study-workshop-content"></div></details>`);
html = html.replace('<div id="player-toolbar">', `<div id="study-hud" role="status" aria-live="polite"></div><button id="study-mute" class="btn" type="button" aria-pressed="true" data-i18n="study.muted">Sound off</button>
<div id="study-status" role="status" aria-live="polite"></div>
<div id="study-notice" hidden><span data-i18n="study.soundQuestion">Sound on?</span><button class="btn" id="study-sound-yes" data-i18n="study.enableSound">Turn on</button><button class="btn" id="study-sound-no" data-i18n="study.notNow">Not now</button></div>
<footer id="study-build" lang="en" data-i18n-ignore>Build 2026-10-28.6</footer>
      <div id="player-toolbar">`);
// Reuse existing locale keys with player-facing copy in the study catalog.
html = html.replace('<div id="player-language"></div>', '<button class="btn" id="study-saves" type="button" data-i18n="study.saves">Saved games</button><div id="player-language"></div>');
html = html.replace('<div id="player-language"></div>', '<button class="btn" id="study-online" type="button" data-i18n="online.title">Online</button><div id="player-language"></div>');
html = html.replace('<div class="canvas-start-actions">', '<div class="canvas-start-actions"><button class="btn" id="study-again" type="button" data-i18n="study.again" hidden>Again</button><button class="btn" id="study-result-menu" type="button" data-i18n="study.menu" hidden>Menu</button>');
player = player.replace('showSlots();\n    });\n    byId(\'player-continue\')', 'selectSlot(activeSlot ?? 0);\n    });\n    byId(\'player-continue\')');
player = player.replace("byId('player-settings').addEventListener", "byId('study-saves').addEventListener('click', () => { engine.closeSettings(); showSlots(); });\n    byId('player-settings').addEventListener");
player = player.replace("page = next;", "page = next;\n      document.body.dataset.studyPage = next;");
html = html.replace(/js\/ramified_minigames_player\.js\?[^"\s]+/, 'js/ramified_minigames_study_player.js?v=20261028-1');
html = html.replace(/(<script src="js\/i18n\/ramified_minigames_locales[^\n]+\n)/, '$1<script src="js/ramified_minigames_study_locales.js?v=20261028-1"></script>\n');
html = html.replace('</body>', '<script src="js/ramified_minigames_study.js?v=20261028-1"></script>\n</body>');
html = html.replace(/js\/ramified_minigames_setup\.js\?[^"\s]+/, `js/ramified_minigames_study_engine.js?v=${BUILD}`);
html = html.replaceAll('20261028-1', BUILD);
// The first rendered home must already use the study's copy and page state.
// Read the English fallbacks from the same catalog used at runtime.
const studyEnglish = {};
require('vm').runInNewContext(fs.readFileSync(path.join(__dirname, 'ramified_minigames_study_locales.js'), 'utf8'), {
  window: { SiteI18n: { register(_namespace, locale, messages) {
    if (locale === 'en') Object.assign(studyEnglish, messages);
  } } }
});
const escapeText = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
for (const id of ['player-new', 'player-online-open']) {
  html = html.replace(new RegExp(`(<button\\b[^>]*\\bid="${id}"[^>]*data-i18n="([^"]+)"[^>]*>)[^<]*(</button>)`),
    (_match, start, key, end) => {
      if (!studyEnglish[key]) throw new Error('Missing study home fallback: ' + key);
      return start + escapeText(studyEnglish[key]) + end;
    });
}
// Resolve the language before body parsing/painting, using the shared resolver.
// The normal DOMContentLoaded init then binds the language controls that did
// not exist in the head and moves the observer from documentElement to body.
const localeScripts = [];
html = html.replace(/<script src="js\/(?:site_i18n|i18n\/ramified_minigames_legacy_sources|i18n\/ramified_minigames_locales|ramified_minigames_study_locales)\.js\?[^"\s]+"><\/script>\n/g,
  script => { localeScripts.push(script.trim()); return ''; });
if (localeScripts.length !== 4) throw new Error('Study locale script anchors missing.');
html = html.replace('</head>', localeScripts.join('\n') + `
<script>
  window.SiteI18n.init({ namespace: 'ramified-minigames', defaultLocale: 'en', supportedLocales: ['en', 'zh-CN'] });
</script>
</head>`);
emit(path.join(root, 'ramified_minigames_study.html'), html);
emit(path.join(__dirname, 'ramified_minigames_study_player.js'), player);
console.log(check ? 'Study build is current.' : 'Built independent player study with isolated save slots.');
