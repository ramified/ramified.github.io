'use strict';
const assert=require('node:assert/strict'),diagnostics=require('./math_workspace_diagnostics.js'),numbers=require('./math_workspace_numbers.js');
numbers.setKernel((value,field)=>{if(field.dataType==='integer'&&!/^-?\d+$/.test(value))throw new Error('This coefficient ring requires an integer.');return {integer:/^-?\d+$/.test(value)?value:null,text:value};});
const ring={kind:'field',id:'R',name:'R',data:{dataType:'rational'}},number={kind:'number',id:'N',name:'a',data:{field:'field:R',hasValue:true,value:'1/2'}},integer={kind:'number',id:'I',name:'g',data:{field:'field:R',hasValue:true,value:'2'}},curve={kind:'variety',type:'curve',id:'C',name:'C',data:{genus:{kind:'reference',ref:'number:I'}}};
const graph=[ring,number,integer,curve];
assert(Object.values(diagnostics.analyze(graph)).every(value=>value.valid));
ring.data.dataType='integer';
let validation=diagnostics.analyze(graph);
assert(validation['field:R'].valid);assert(!validation['number:N'].valid);assert(validation['number:I'].valid);assert(validation['variety:C'].valid);
assert.match(diagnostics.messages(validation['number:N'],graph).join(' '),/1\/2.*R.*integer/);
assert.equal(number.data.value,'1/2','diagnosis never modifies definitions');
ring.data.dataType='rational';integer.data.value='3/2';
validation=diagnostics.analyze(graph);assert(validation['number:I'].valid);assert(!validation['variety:C'].valid);
const extension={kind:'field-extension',id:'E',name:'L',data:{base:'field:R'}};
ring.data.dataType='integer';validation=diagnostics.analyze([...graph,extension]);
assert(!validation['field-extension:E'].valid);assert(validation['field:R'].valid);
ring.data.dataType='rational';integer.data.value='3';
assert(Object.values(diagnostics.analyze([...graph,extension])).every(value=>value.valid),'repairs clear derived diagnostics');
console.log('Dependency diagnostics: independent upstream definitions, transitive invalidation, preserved values and repair passed');
