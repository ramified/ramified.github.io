'use strict';
const assert=require('node:assert/strict'),model=require('./math_workspace_panel_registry.js');
const input={id:'number-input',input:'number'},view={id:'number-view'},calc={id:'lr'},overview={id:'sheaf-view',overview:true};
const live=new Set(['number:a','number:b','young:a','young:b']),registry=model.create(key=>live.has(key));
const panel=(id,definition,assetKey='',refs={})=>({id,definition,assetKey,closed:false,computation:definition.input?null:{refs}});
const a=panel('1',input,'number:a');registry.register(a);
assert.equal(registry.find(input,'number:a'),a);assert.equal(registry.find(input,'number:b'),null);
const b=panel('2',view,'',{asset:'number:a'});registry.register(b);
assert.equal(registry.find(view,'',{asset:'number:a'}),b);
assert.equal(registry.find(input,'number:a'),a,'Modify and Display have different identities');
b.closed=true;assert.equal(registry.find(view,'',{asset:'number:a'}),b,'closed instances remain reusable');
const comparison=panel('3',view,'',{asset:'number:a'});comparison.comparison=true;registry.register(comparison);
assert.equal(registry.find(view,'',{asset:'number:a'}),b,'ordinary opening prefers the primary view');
assert.equal(comparison.comparisonIndex,2);
const legacy=panel('4',input,'number:a');registry.register(legacy);assert.equal(legacy.comparison,true,'legacy duplicate drafts are retained as saved copies');
assert.notEqual(model.identity(calc,'',{lambda:'young:a',mu:'young:b'}),model.identity(calc,'',{lambda:'young:b',mu:'young:a'}),'operand order matters');
assert.equal(model.identity(overview,'',{nodes:['number:a','number:b'],active:'number:a',asset:'number:a'}),model.identity(overview,'',{nodes:['number:b','number:a'],active:'number:b',asset:'number:b'}),'selection and set ordering do not create new overview identities');
const calculation=panel('5',calc,'',{lambda:'young:a',mu:'young:b'});registry.register(calculation);
assert.equal(registry.find(calc,'',{lambda:'young:a'}),calculation,'unspecified inputs preserve the existing choices');
calculation.computation.refs.lambda='young:b';registry.register(calculation);
assert.equal(registry.find(calc,'',{lambda:'young:a'}),null,'retargeting removes the old binding');
assert.equal(registry.find(calc,'',{lambda:'young:b'}),calculation);
const diagrams={id:'complex-diagrams',structureScene:true},shared=panel('6',diagrams,'',{nodes:['complex:a']});
registry.register(shared);
const diagramCopy=panel('7',diagrams,'',{nodes:['filtration:b']});diagramCopy.comparison=true;registry.register(diagramCopy);
shared.computation.refs.nodes=['filtration:b'];registry.register(shared);
assert.equal(shared.comparison,undefined,'changing common-display membership does not turn it into a comparison');
assert.equal(registry.find(diagrams,'',{nodes:['complex:a']}),shared,'common displays keep a stable identity across member sets');
live.delete('number:a');registry.sync([a,b,comparison,legacy,calculation]);
assert.equal(registry.find(input,'number:a'),null,'deleted targets are unregistered');
registry.sync([]);assert.equal(registry.size,0);registry.clear();assert.equal(registry.size,0);
console.log('Panel registry: asset/view identities, ordered operands, retargeting, closed reuse, comparison copies and cleanup passed');
