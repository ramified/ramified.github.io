'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { startServer, launchBrowser, stopBrowser, waitFor, evaluate, mouse } = require('./math_workspace_drag_regression_test.js');
async function run() {
  const server = await startServer(); let session;
  try {
    session = await launchBrowser('http://127.0.0.1:' + server.address().port + '/math_workspace.html');
    const { client } = session, errors = [];
    const read = (fn, ...args) => evaluate(client, '(' + fn.toString() + ')(...' + JSON.stringify(args) + ')');
    await client.send('Runtime.enable'); await client.send('Page.enable');
    client.socket.addEventListener('message', event => { const msg = JSON.parse(String(event.data)); if (msg.method === 'Runtime.exceptionThrown') errors.push(msg.params.exceptionDetails.exception?.description || msg.params.exceptionDetails.text); });
    await waitFor(() => read(() => !!window.MathWorkspaceObjectPanels), 20000);
    await read(() => {
      window.api = MathWorkspaceAssetsTest; window.panels = MathWorkspaceObjectPanels;
      window.lie = api.createObjectAsset('lie', { data: { family: 'A', rank: 4 } });
      window.d = api.createObjectAsset('dynkin', { data: { lie: 'lie:' + lie.id, vertices: [1,3] } });
      window.w = api.createObjectAsset('strands', { data: { lie: 'lie:' + lie.id, generators: [{ family: 'coxeter', index: 1 }, { family: 'coxeter', index: 2 }] } });
      window.di = panels.open('dynkin-input', 'dynkin:' + d.id, 'side');window.dv=panels.open('dynkin-view','dynkin:'+d.id,'main');
      window.vertex = panels.open('dynkin-vertex', 'dynkin:' + d.id, 'side');
      window.parabolic = panels.open('dynkin-parabolic', 'dynkin:' + d.id, 'side');
      window.cartan = panels.open('dynkin-cartan', 'dynkin:' + d.id, 'side');
      window.ar = panels.open('dynkin-starting', 'dynkin:' + d.id, 'side');
    });
    assert.deepEqual(errors, []);
    assert.equal(await read(() => cartan.computation.refs.lie), 'lie:' + await read(() => lie.id));
    assert.equal(await read(() => cartan.propertyRenderer.editor.readObjectResult().cartan.length), 4);
    assert.deepEqual(await read(() => parabolic.propertyRenderer.editor.readObjectResult().vertices), [1,3]);
    await read(() => { const field = vertex.propertyRenderer.editor.inspectorShadow.querySelector('[aria-label="Property vertex"]'); field.value = '2'; field.dispatchEvent(new Event('change',{ bubbles: true })); });
    assert.equal(await read(() => vertex.propertyRenderer.editor.readObjectResult().vertex), 3);
    assert.deepEqual(await read(() => api.localAssetSnapshot().assets.find(a => a.id === d.id).data.vertices), [1,3]);
    const clickDynkin = async edge => {
      const point = await read(async edge => {
        const canvas = dv.propertyRenderer.editor.shadow.querySelector('#dynkin-canvas'); canvas.scrollIntoView({ block: 'center' });
        await new Promise(requestAnimationFrame);
        const rect = canvas.getBoundingClientRect(), geometry = dv.propertyRenderer.editor.objectIO('geometry');
        const hit = edge ? geometry.edges[0] : geometry.vertices[1];
        const x = edge ? (hit.x1 + hit.x2) / 2 : hit.x, y = edge ? (hit.y1 + hit.y2) / 2 : hit.y;
        return { x: rect.left + x * rect.width / 900, y: rect.top + y * rect.height / 360 };
      }, edge);
      await mouse(client,'mousePressed',point.x,point.y,1); await mouse(client,'mouseReleased',point.x,point.y,0);
    };
    await clickDynkin(false);
    await waitFor(() => read(() => api.localAssetSnapshot().assets.find(a => a.id === d.id).data.vertices.length === 3));
    await clickDynkin(false);
    await waitFor(() => read(() => api.localAssetSnapshot().assets.find(a => a.id === d.id).data.vertices.length === 2));
    assert.equal(await read(() => ar.propertyRenderer.editor.inspectorShadow.querySelector('#dynkin-starting-ar-mode').disabled), true);
    await read(() => di.quiver.click());
    assert.deepEqual(await read(() => api.localAssetSnapshot().assets.find(a => a.id === d.id).data.quiver), { '0-1': 1,'1-2': 1,'2-3': 1 });
    await clickDynkin(true);
    await waitFor(() => read(() => api.localAssetSnapshot().assets.find(a => a.id === d.id).data.quiver['0-1'] === -1));
    await read(() => { const q = dv.propertyRenderer.editor.shadow.querySelector('#dynkin-quiver-mode'); q.click(); });
    assert.equal(await read(() => api.localAssetSnapshot().assets.find(a => a.id === d.id).data.quiver['0-1']), -1, 'hiding arrows preserves mathematical directions');
    await read(() => ar.propertyRenderer.editor.inspectorShadow.querySelector('#dynkin-starting-ar-mode').click());
    assert.equal(await read(() => ar.propertyRenderer.editor.captureAssetProperties().arMode), true);
    const dynkinShot = await client.send('Page.captureScreenshot',{ format: 'png' }); fs.writeFileSync(path.join(os.tmpdir(),'math-workspace-dynkin.png'),Buffer.from(dynkinShot.data,'base64'));
    await read(() => {
      window.si = panels.open('strands-input','strands:' + w.id,'main');
      window.si2 = panels.open('strands-input','strands:' + w.id,'side');
      window.info = panels.open('strands-info','strands:' + w.id,'side');
      window.calc = panels.open('strands-calculation','strands:' + w.id,'side');
      window.basis = panels.open('strands-basis','strands:' + w.id,'side');
      window.relations = panels.open('strands-relations','','side');
      window.sv=panels.open('strands-view','strands:'+w.id,'main');window.sv2=panels.open('strands-view','strands:'+w.id,'side');window.display = panels.open('strands-display','','side');
      display.viewSelect.value = sv.id; display.viewSelect.dispatchEvent(new Event('change',{ bubbles: true }));
    });
    assert.deepEqual(errors, []);
    assert.equal(await read(() => info.propertyRenderer.editor.readObjectResult().strandCount), 5);
    assert.equal(await read(() => basis.computation.refs.lie), 'lie:' + await read(() => lie.id));
    assert.equal(await read(() => relations.computation.status), 'current');
    assert.equal(await read(() => panels.listCards().some(c => /Input/.test(c.label))), false);
    assert.equal(await read(() => [...document.querySelector('#workspace-open-canvas').options].some(o => ['dynkin','strands'].includes(o.value))), false);
    await read(() => {
      const root = calc.propertyRenderer.editor.inspectorShadow, target = root.querySelector('#strand-calculation-target');
      target.value = 'symmetric'; target.dispatchEvent(new Event('change',{ bubbles: true })); root.querySelector('#strand-calculate').click();
    });
    await waitFor(() => read(() => calc.computation.status === 'current'));
    assert.equal(await read(() => calc.propertyRenderer.editor.readObjectResult().hasResult), true);
    const wordBefore = await read(() => api.localAssetSnapshot().assets.find(a => a.id === w.id).data);
    await read(() => {
      const dir = display.propertyRenderer.editor.inspectorShadow.querySelector('#strand-direction'); dir.value = 'left-right'; dir.dispatchEvent(new Event('change',{ bubbles: true }));
    });
    await waitFor(() => read(() => sv.propertyRenderer.editor.objectIO('view').direction === 'left-right'));
    assert.equal(await read(() => sv2.propertyRenderer.editor.objectIO('view').direction), 'up-down');
    assert.deepEqual(await read(() => api.localAssetSnapshot().assets.find(a => a.id === w.id).data), wordBefore);
    assert.equal(await read(() => calc.computation.status), 'current');
    const basisSignature = await read(() => basis.computation.signature);
    await read(() => si.activeRenderer.editor.inspectorShadow.querySelector('[data-generator-family="braid"]').click());
    await waitFor(() => read(() => api.localAssetSnapshot().assets.find(a => a.id === w.id).data.generators.length === 3));
    assert.equal(await read(() => calc.computation.status), 'stale');
    assert.equal(await read(() => JSON.parse(panels.exportText('property:' + calc.computation.id)).result), null);
    assert.equal(await read(() => basis.computation.signature), basisSignature);
    const strandShot = await client.send('Page.captureScreenshot',{ format: 'png' }); fs.writeFileSync(path.join(os.tmpdir(),'math-workspace-strands.png'),Buffer.from(strandShot.data,'base64'));
    await read(() => api.updateObjectAsset({ kind: 'lie', id: lie.id },{ data: { family: 'A', rank: 1 } }));
    assert.equal(await read(() => calc.computation.status), 'missing');
    assert.equal(await read(() => vertex.computation.status), 'missing');
    assert.equal(await read(() => api.localAssetSnapshot().assets.find(a => a.id === w.id).data.generators.length), 3);
    assert.deepEqual(await read(() => api.localAssetSnapshot().assets.find(a => a.id === d.id).data.vertices), [1,3]);
    await read(() => { window.li = panels.open('lie-input','lie:' + lie.id,'side'); li.rank.focus(); });
    for (const type of ['keyDown','keyUp']) await client.send('Input.dispatchKeyEvent',{ type,key:'a',code:'KeyA',windowsVirtualKeyCode:65,modifiers:2 });
    for (const type of ['keyDown','keyUp']) await client.send('Input.dispatchKeyEvent',{ type,key:'Backspace',code:'Backspace',windowsVirtualKeyCode:8 });
    assert.equal(await read(() => li.rank.value), '');
    assert.equal(await read(() => api.localAssetSnapshot().assets.find(a => a.id === lie.id).data.rank), 1);
    await client.send('Input.insertText',{ text:'1' }); await client.send('Input.insertText',{ text:'3' });
    assert.equal(await read(() => li.rank.value), '13');
    assert.equal(await read(() => info.propertyRenderer.editor.readObjectResult().strandCount), 14);
    assert.equal(await read(() => cartan.computation.status), 'missing');
    await read(() => li.rank.blur());
    const beforeInvalid = await read(() => api.localAssetSnapshot());
    assert.equal(await read(() => { try { panels.importText('strands:' + w.id,JSON.stringify({ kind:'strand-diagram-calculator',version:4,groupType:'symmetric',strandCount:3,appliedGenerators:[{ family:'coxeter',index:9 }] })); return false; } catch (_) { return true; } }), true);
    assert.deepEqual(await read(() => api.localAssetSnapshot()), beforeInvalid);
    await read(() => panels.importText('strands:' + w.id,JSON.stringify({ kind:'strand-diagram-calculator',version:4,groupType:'B',strandCount:3,appliedGenerators:[{ family:'braid',index:0,sign:-1 },{ family:'kl',index:1 }] })));
    assert.equal(await read(() => api.localAssetSnapshot().assets.find(a => a.id === lie.id).data.rank), 13, 'import must never overwrite the existing shared Lie');
    assert.equal(await read(() => info.propertyRenderer.editor.readObjectResult().groupType), 'B');
    assert.equal(await read(() => sv.propertyRenderer.editor.objectIO('view').direction), 'left-right');
    assert.match(await read(() => panels.exportText('strands:' + w.id,'latex')), /mixed typed word/);
    await read(() => { panels.move(si,'side'); panels.move(si,'hidden'); window.reopened = panels.open('strands-input','strands:' + w.id,'main'); });
    assert.equal(await read(() => reopened.id), await read(() => si.id));
    assert.equal(await read(() => sv.propertyRenderer.editor.objectIO('view').direction), 'left-right');
    await read(() => {
      const empty = api.createObjectAsset('strands', { data: { lie: '' } }); window.emptyPanel = panels.open('strands-input','strands:' + empty.id,'main');
      window.largeDynkin = panels.open('dynkin-input','dynkin:' + d.id,'main');
    });
    assert.equal(await read(() => !!emptyPanel.activeRenderer), false, 'an unbound Input must not display a fabricated default object');
    assert.equal(await read(() => !!largeDynkin.activeRenderer), false, 'an unsupported Lie rank must be checked before mounting');
    await read(() => panels.importText('dynkin:' + d.id,JSON.stringify({ calculator:'Dynkin diagram calculator',version:1,typeKey:'D',rank:4,selectedVertices:[1,4],quiver:{enabled:true,orientations:{'0-1':-1,'1-2':1,'1-3':1}} })));
    assert.deepEqual(await read(() => dv.propertyRenderer.editor.collectAssets().data.vertices), [1,4]);
    assert.equal(await read(() => cartan.computation.status), 'missing', 'a direct Lie property keeps its original explicit reference when the Dynkin object is retargeted');
    assert.equal(await read(() => ar.computation.status), 'current');
    const exported = await read(() => panels.exportText('dynkin:' + d.id));
    await read(text => panels.importText('dynkin:' + d.id,text), exported);
    assert.equal(await read(() => panels.exportText('dynkin:' + d.id)), exported);
    await read(() => { document.querySelector('#workspace-add-card').click(); document.querySelector('#workspace-card-options input[data-card-key="' + calc.id + '"]').click(); });
    assert.equal(await read(() => calc.closed), true);
    await read(() => { document.querySelector('#workspace-card-options input[data-card-key="' + calc.id + '"]').click(); document.querySelector('#workspace-add-card').click(); });
    assert.equal(await read(() => calc.closed), false);
    await client.send('Emulation.setDeviceMetricsOverride',{ width:760,height:1000,deviceScaleFactor:1,mobile:false });
    assert.equal(await read(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    assert.deepEqual(errors, []);
    console.log('math_workspace_root_system_ui_test: native Dynkin/Strands, shared Lie, property focus, quivers, typed words, calculation invalidation, independent views, drafts and atomic legacy imports passed');
  } finally { if (session) { session.client.close(); await stopBrowser(session.browser,session.profile); } await new Promise(resolve => server.close(resolve)); }
}
run().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
