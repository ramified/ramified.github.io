'use strict';
const assert=require('node:assert/strict'),rings=require('./math_workspace_rings.js'),objects=require('./math_workspace_objects.js'),structures=require('./math_workspace_structures.js');
const asset=(id,dataType)=>({kind:'field',id,type:'field',data:objects.normalize('field','field',{dataType})});
const z=asset('Z','integer'),q=asset('Q','rational');
assert(rings.isRing(z));assert(!rings.isField(z));assert(rings.isField(q));
for(const type of ['complex','real','rational','finite-field','finite-extension','rational-function','function-field','number-field'])assert(rings.isField(asset(type,type)),type);
assert(!rings.isField({kind:'matrix',data:{dataType:'rational'}}));
assert.match(rings.classification(z.data),/not a field/);
assert.equal(objects.kindLabels.field,'Ring');
const spec={kind:'field',requiresField:true},definition={};
assert(!objects.compatible(z,spec,definition));assert(objects.compatible(q,spec,definition));
assert(objects.compatible(z,{kind:'field'},definition),'ordinary coefficient references accept rings');
const extension={kind:'field-extension',id:'E',data:structures.normalize('field-extension',{base:'field:Q'})};
assert.deepEqual(structures.issues(extension,[q]),[]);
assert.throws(()=>rings.validateGraph([{...extension,data:{...extension.data,base:'field:Z'}},z]),/base field/);
assert.throws(()=>rings.validateGraph([{...extension,data:{...extension.data,target:'field:Z'}},q,z]),/target/);
const functionField={...asset('K','function-field'),data:{...asset('K','function-field').data,constantField:'field:Z'}};
assert.throws(()=>rings.validateGraph([z,functionField]),/constant field/);
assert.deepEqual(structures.issues({...functionField,data:{...functionField.data,constantField:'field:Q'}},[q]),[]);
console.log('Ring model: integer ring, field classification, typed references and extension/constant-field constraints passed');
