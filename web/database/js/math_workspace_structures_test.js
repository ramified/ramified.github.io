'use strict';
const assert=require('node:assert/strict'),model=require('./math_workspace_structures.js');
const base={kind:'field',id:'Q',data:{dataType:'rational'}},extension={kind:'field-extension',id:'E',data:model.normalize('field-extension',{base:'field:Q'})};
assert.equal(model.extensionInput(extension,[base]).baseKind,'Q');
const relative={...base,data:{dataType:'number-field',numberFieldPolynomial:'x^2-2'}};
assert.equal(model.extensionInput(extension,[relative]).baseKind,'lmfdb');
assert.throws(()=>model.extensionInput(extension,[{...base,data:{dataType:'real'}}]),/no base-field substitution/);
assert.throws(()=>model.extensionInput({...extension,data:{...extension.data,embedding:'a -> -a'}},[base]),/not yet supported/);
const complex={kind:'complex',id:'C',data:model.normalize('complex',{objects:[{symbol:'E',ref:'sheaf:E'},'F'],maps:['d']})};
assert.deepEqual(model.references('complex',complex.data),['sheaf:E']);
assert.equal(model.complexEntry(complex,[{kind:'sheaf',id:'E',name:'G'}]).objects[0],'G');
assert.equal(model.complexEntry(complex,[]).objects[0],'E');
assert.throws(()=>model.normalize('complex',{objects:['A','B'],maps:[]}),/differential/);
assert.throws(()=>model.normalize('complex',{condition:'verified'}),/certificate/);
const legacy={kind:'chain-complex',objects:['A','B'],maps:['f'],display:'snake-les',snakeLayout:{firstRowSize:3,startIndex:0}};
assert.deepEqual(model.fromComplexEntry(legacy).legacy,legacy);
const filtration={kind:'filtration',id:'F',data:model.normalize('filtration',{objects:['A','B','C'],quotients:['G','H'],direction:'decreasing',startDegree:-2})};
assert.deepEqual(model.complexEntry(filtration,[]).objects,['C','B','A']);
assert.deepEqual(model.complexEntry(filtration,[]).quotients,['H','G']);
assert.deepEqual(model.fromComplexEntry({...legacy,kind:'filtration',quotients:['G']}).quotients,[{symbol:'G',ref:''}]);
assert.throws(()=>model.normalize('filtration',{objects:['A','B'],quotients:[]}),/subquotient/);
assert.throws(()=>model.normalize('filtration',{condition:'verified'}),/certificate/);
assert.equal(model.issues({kind:'filtration',data:model.normalize('filtration',{objects:['A','B'],quotients:[{symbol:'G',ref:'field:Q'}]})},[base]).length,1);
const objects=require('./math_workspace_objects.js');
const constant={kind:'field',id:'k',data:objects.normalize('field','field',{dataType:'finite-extension',finiteFieldPrime:3,finiteFieldDegree:2})};
const functionBase={kind:'field',id:'Q',data:objects.normalize('field','field',{dataType:'function-field',constantField:'field:k'})};
assert.equal(model.extensionInput(extension,[constant,functionBase]).q,'9');
assert.equal(model.extensionInput(extension,[constant,functionBase]).baseKind,'Fqt');
assert.throws(()=>model.extensionInput(extension,[constant,{...functionBase,data:{...functionBase.data,functionFieldPolynomial:'u^2-t'}}]),/algebraic function-field base/);
assert.throws(()=>model.extensionInput(extension,[constant,{...functionBase,data:{...functionBase.data,rationalFunctionVariables:['s','t']}}]),/single base variable/);
assert.throws(()=>objects.normalize('field','field',{dataType:'finite-extension',finiteFieldPrime:6}),/prime/);
assert.throws(()=>objects.normalize('field','field',{dataType:'function-field',rationalFunctionVariables:['u']}),/separate algebraic generator/);
assert.equal(model.issues(functionBase,[]).length,1);
const context=objects.contextFor({type:'field-extension-view',refs:{asset:'field-extension:E'}},[extension,functionBase,constant]);
assert.equal(context.objects['field:k'].data.finiteFieldDegree,2,'include transitive constant fields in computation signatures');
assert.deepEqual(context.missing,[]);
assert.equal(model.issues(complex,[]).length,1);
console.log('PASS structure normalization, symbolic references, relative fields, unsupported capabilities and lossless complex metadata');
